#!/usr/bin/env python3
from __future__ import annotations

import json
import re
from pathlib import Path

root = Path(__file__).resolve().parents[1]
records = json.loads((root / "cases" / "CASE_INDEX.json").read_text(encoding="utf-8"))
ids = [record["public_id"] for record in records]
if len(ids) != len(set(ids)):
    raise SystemExit("duplicate public case identifiers")
for record in records:
    case_dir = root / "cases" / record["category"] / record["name"]
    for name in ("README.md", "case.json"):
        if not (case_dir / name).is_file():
            raise SystemExit(f"missing {case_dir / name}")

private_pattern = re.compile(r"/Users/|BEGIN (?:RSA|OPENSSH|EC) PRIVATE KEY|(?:api[_-]?key|token)\s*[:=]", re.I)
assistant_pattern = re.compile(
    r"\b(?:Codex|ChatGPT|OpenAI|Claude|Anthropic|Gemini|Copilot)\b"
    r"|generated by (?:an? )?AI|large language model|artificial intelligence",
    re.I,
)
internal_pattern = re.compile(
    r"pre[- ]?release|post[- ]?acceptance|release candidate|author workspace"
    r"|README[- ]?V\d+|reviewer[- ]?closure",
    re.I,
)
if not (root / "LICENSE").is_file():
    raise SystemExit("missing top-level LICENSE")
if (root / "LICENSE_PENDING.md").exists():
    raise SystemExit("placeholder licence file must not be published")
for path in root.rglob("*"):
    if not path.is_file() or path.suffix.lower() not in {".py", ".md", ".json", ".yml", ".yaml", ".sh", ".toml", ".cff", ".txt", ".csv"}:
        continue
    if path.name in {"validate_repository.py", "build_github_release.py"}:
        continue
    text = path.read_text(encoding="utf-8", errors="ignore")
    if private_pattern.search(text):
        raise SystemExit(f"private-path or credential-like text in {path.relative_to(root)}")
    if assistant_pattern.search(text):
        raise SystemExit(f"assistant-related text in {path.relative_to(root)}")
    if internal_pattern.search(text):
        raise SystemExit(f"internal workflow text in {path.relative_to(root)}")
print(f"repository validation passed: {len(records)} indexed entries")
